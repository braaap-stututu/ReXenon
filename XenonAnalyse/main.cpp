#include <cassert>
#include <iterator>
#include <file.h>
#include <disasm.h>
#include <image.h>
#include <xbox.h>
#include <fmt/core.h>
#include "function.h"
#include "switch_tables.h"
#include <fstream>

static std::string out;

template<class... Args>
static void println(fmt::format_string<Args...> fmt, Args&&... args)
{
    fmt::vformat_to(std::back_inserter(out), fmt.get(), fmt::make_format_args(args...));
    out += '\n';
};

int main(int argc, char** argv)
{
    if (argc < 3)
    {
        printf("Usage: XenonAnalyse [input XEX file path] [output jump table TOML file path]");
        return EXIT_SUCCESS;
    }

    const auto file = LoadFile(argv[1]);
    auto image = Image::ParseImage(file.data(), file.size());

    auto printTable = [&](const SwitchTable& table)
        {
            println("[[switch]]");
            println("base = 0x{:X}", table.base);
            println("r = {}", table.r);
            println("default = 0x{:X}", table.defaultLabel);
            println("labels = [");
            for (const auto& label : table.labels)
            {
                println("    0x{:X},", label);
            }

            println("]");
            println("");
        };

    println("# Generated by XenonAnalyse");

    auto printAll = [&](SwitchTableType type)
        {
            for (const auto& table : FindSwitchTables(image, type))
                printTable(table);
        };

    println("# ---- ABSOLUTE JUMPTABLE ----");
    printAll(SWITCH_ABSOLUTE);

    println("# ---- COMPUTED JUMPTABLE ----");
    printAll(SWITCH_COMPUTED);

    println("# ---- OFFSETED JUMPTABLE ----");
    printAll(SWITCH_BYTEOFFSET);
    printAll(SWITCH_SHORTOFFSET);

    std::ofstream f(argv[2]);
    f.write(out.data(), out.size());

    return EXIT_SUCCESS;
}
